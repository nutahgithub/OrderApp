const dictionaries: Record<Locale, MessageDictionary> = {
  en,
  vi
};

type Values = Record<string, string | number>;

export const t = (key: MessageKey, locale: Locale = defaultLocale, values: Values = {}): string => {
  const template = dictionaries[locale][key] ?? dictionaries[defaultLocale][key];

  return Object.entries(values).reduce((message, [name, value]) => {
    return message.replaceAll(`{{${name}}}`, String(value));
  }, template);
};
